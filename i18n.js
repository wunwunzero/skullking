// Translations. English text is the key (and the fallback); each phone picks its own language.
// t('Round {r}', { r: 3 }) fills {placeholders}; tn() picks the singular or plural English key.

export const LANGS = { en: 'English', zh: '中文', ms: 'Bahasa Melayu' };

let lang = 'en';
try {
  const saved = localStorage.getItem('sk.lang');
  const nav = (navigator.language || '').toLowerCase();
  lang = LANGS[saved] ? saved : nav.startsWith('zh') ? 'zh' : nav.startsWith('ms') ? 'ms' : 'en';
} catch {}
const htmlLang = { en: 'en', zh: 'zh-Hans', ms: 'ms' };
if (typeof document !== 'undefined') document.documentElement.lang = htmlLang[lang];

export const getLang = () => lang;
export function setLang(l) {
  if (!LANGS[l]) return;
  lang = l;
  try { localStorage.setItem('sk.lang', l); } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = htmlLang[l];
}

export function t(s, p) {
  const out = (lang !== 'en' && DICT[lang][s]) || s;
  return p ? out.replace(/\{(\w+)\}/g, (m, k) => (p[k] ?? m)) : out;
}
export const tn = (n, one, other, p) => t(n === 1 ? one : other, { n, ...p });

export function ordinal(n) {
  if (lang === 'zh') return `第${n}名`;
  if (lang === 'ms') return `ke-${n}`;
  return n + (n % 10 === 1 && n % 100 !== 11 ? 'st' : n % 10 === 2 && n % 100 !== 12 ? 'nd' : n % 10 === 3 && n % 100 !== 13 ? 'rd' : 'th');
}

